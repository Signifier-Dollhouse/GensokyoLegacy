package dev.xkmc.gensokyolegacy.content.attachment.party.core;

import dev.xkmc.gensokyolegacy.content.entity.module.PartyModule;
import dev.xkmc.gensokyolegacy.content.entity.youkai.YoukaiEntity;
import dev.xkmc.gensokyolegacy.init.GensokyoLegacy;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Holder;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.storage.loot.LootParams;
import net.minecraft.world.level.storage.loot.LootTable;
import net.minecraft.world.level.storage.loot.parameters.LootContextParamSets;
import net.minecraft.world.level.storage.loot.parameters.LootContextParams;
import net.minecraft.world.phys.Vec3;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;

/**
 * What a guest leaves behind when the spread runs out.
 * <p>
 * Each character has her own loot table, at
 * {@code <namespace>:party_gift/<entity type path>} — {@code gensokyolegacy:party_gift/cirno}
 * and so on — so what she gives and how generous she is about it are both data rather
 * than a weighted draw rebuilt out of the item registry at the moment she leaves. The
 * tables are generated by {@code GiftLootGen}.
 * <p>
 * A character with no table of her own falls back to {@link #DEFAULT_TABLE}, which is the
 * same ladder with an even spread over the gift items. That is what makes a new party
 * guest a one-line change: an author who gives her a {@code party_taste} and no table of
 * her own still leaves gifts behind, rather than nothing on the table.
 * <p>
 * The gift is dropped on the table with {@link Block#popResource} rather than
 * granted into an inventory, which is the in-tree idiom for putting an item down
 * in the world. Nothing here needs unwinding when the real gift item is designed.
 */
public class PartyGift {

	/** Folder the gift tables live in, under their own character type's namespace. */
	public static final String TABLE_DIR = "party_gift";

	/** Used for a guest who has no table of her own. */
	public static final ResourceKey<LootTable> DEFAULT_TABLE =
			ResourceKey.create(Registries.LOOT_TABLE, GensokyoLegacy.loc(TABLE_DIR + "/default"));

	/**
	 * Drop a gift on the guest's table, once per visit.
	 * <p>
	 * A guest with nothing tasteful to give leaves nothing rather than something
	 * arbitrary.
	 * <p>
	 * What makes her generous is **the appeal she personally consumed** rather than whether
	 * she was satisfied. Those are two of the three food measurements (design doc §5.2) and
	 * they answer different questions: rare-effect delicacies fill her up no better than
	 * plain bread does, and she is still more moved by them. An earlier version halved the
	 * gift for an under-served guest, which made a beautiful thin spread read as stingy
	 * rather than as modest — the host's generosity and the guest's appetite are not one
	 * axis.
	 * <p>
	 * It never shows as a bigger stack: a gift is **always exactly one item**, and what the
	 * appeal buys is <i>reach</i> — the better things, and eventually something of her own,
	 * enter her table and are there to be picked. That lives in her loot table as entries
	 * gated on {@link AppealConsumedCondition}, and it is why a single pool of one roll is
	 * enough to express a whole ladder.
	 * <p>
	 * <b>Once.</b> She leaves through two doors — running out of food she can reach, or
	 * rolling {@code leaveChance} — and a visit can pass near enough to both that she
	 * would otherwise thank the host twice for one banquet. The flag lives on her module
	 * rather than here, so it survives the two calls and any task restart between them.
	 *
	 * @return whether a gift was left
	 */
	public static boolean give(ServerLevel level, YoukaiEntity guest, PartyModule party) {
		if (party.gifted()) return false;
		var table = party.table();
		if (table == null) return false;
		var gift = roll(level, guest, table);
		if (gift == null) return false;
		party.markGifted();
		Block.popResource(level, table.above(), gift);
		return true;
	}

	/**
	 * One gift out of her table, or null if she has nothing to give.
	 * <p>
	 * The guest goes in as {@link LootContextParams#THIS_ENTITY} and the table as the
	 * origin, which is what {@link AppealConsumedCondition} reads to size her generosity;
	 * that is also why these tables are generated against
	 * {@link LootContextParamSets#ADVANCEMENT_REWARD}, the only stock param set that
	 * carries both.
	 */
	@Nullable
	private static ItemStack roll(ServerLevel level, YoukaiEntity guest, BlockPos table) {
		var loot = tableOf(level, guest);
		if (loot == null) return null;
		var params = new LootParams.Builder(level)
				.withParameter(LootContextParams.THIS_ENTITY, guest)
				.withParameter(LootContextParams.ORIGIN, Vec3.atCenterOf(table.above()))
				.create(LootContextParamSets.ADVANCEMENT_REWARD);
		var stacks = new ArrayList<ItemStack>();
		loot.getRandomItems(params, stacks::add);
		// One gift, ever. A generated table is a single pool of a single roll, so this costs
		// nothing — but a datapack that rewrites a table into two pools would otherwise bury
		// the table under both, and that should read as a mistake in the data rather than one
		// in here.
		return stacks.isEmpty() ? null : stacks.getFirst();
	}

	/**
	 * Her own table, or {@link #DEFAULT_TABLE} when she has not got one.
	 * <p>
	 * The reloadable registries answer {@code LootTable.EMPTY} for a table that was never
	 * defined, which is indistinguishable from a table defined to give nothing — so this
	 * asks the lookup directly, because "no table" wants the fallback and "an empty table"
	 * does not.
	 */
	@Nullable
	private static LootTable tableOf(ServerLevel level, YoukaiEntity guest) {
		var lookup = level.getServer().reloadableRegistries().get().lookup(Registries.LOOT_TABLE).orElse(null);
		if (lookup == null) return null;
		var id = BuiltInRegistries.ENTITY_TYPE.getKey(guest.getType());
		if (id == null) return null;
		var own = ResourceKey.create(Registries.LOOT_TABLE,
				ResourceLocation.fromNamespaceAndPath(id.getNamespace(), TABLE_DIR + "/" + id.getPath()));
		return lookup.get(own).or(() -> lookup.get(DEFAULT_TABLE)).map(Holder::value).orElse(null);
	}

	private PartyGift() {
	}

}